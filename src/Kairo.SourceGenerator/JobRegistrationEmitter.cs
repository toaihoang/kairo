using System.Globalization;
using System.Text;

namespace Kairo.SourceGenerator;

/// <summary>
/// Writes the C# source of the generated <c>AddKairoJobs()</c> extension method.
/// </summary>
internal static class JobRegistrationEmitter
{
    public const string HintName = "KairoJobRegistrations.g.cs";

    private const string ServiceProviderExtensions = "global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions";

    public static string Emit(IReadOnlyList<JobModel> jobs)
    {
        StringBuilder source = new StringBuilder();
        source.AppendLine("// <auto-generated/>");
        source.AppendLine("#nullable enable");
        source.AppendLine();
        source.AppendLine("namespace Kairo");
        source.AppendLine("{");
        source.AppendLine("    /// <summary>Registers the classes marked with [Job] in this assembly.</summary>");
        source.AppendLine("    [global::System.CodeDom.Compiler.GeneratedCode(\"Kairo.SourceGenerator\", \"1.0.0\")]");
        source.AppendLine("    internal static class KairoJobRegistrations");
        source.AppendLine("    {");
        source.AppendLine("        /// <summary>Registers every [Job] class of this assembly. Jobs are created without reflection.</summary>");
        source.AppendLine("        public static global::Kairo.KairoBuilder AddKairoJobs(this global::Kairo.KairoBuilder builder)");
        source.AppendLine("        {");

        foreach (JobModel job in jobs)
        {
            AppendRegistration(source, job);
        }

        source.AppendLine("            return builder;");
        source.AppendLine("        }");
        source.AppendLine("    }");
        source.AppendLine("}");
        return source.ToString();
    }

    private static void AppendRegistration(StringBuilder source, JobModel job)
    {
        string typeArguments = job.JobTypeName;
        if (job.PayloadTypeName is not null)
        {
            typeArguments = job.JobTypeName + ", " + job.PayloadTypeName;
        }

        source.AppendLine("            builder.AddJob<" + typeArguments + ">(");
        source.AppendLine("                " + ToStringLiteral(job.JobName) + ",");
        source.AppendLine("                services => new " + job.JobTypeName + "(" + BuildConstructorArguments(job) + "),");
        AppendConfigure(source, job);
        source.AppendLine();
    }

    private static string BuildConstructorArguments(JobModel job)
    {
        List<string> arguments = new List<string>();
        foreach (ConstructorParameterModel parameter in job.ConstructorParameters)
        {
            arguments.Add(BuildArgument(parameter));
        }

        return string.Join(", ", arguments);
    }

    private static string BuildArgument(ConstructorParameterModel parameter)
    {
        switch (parameter.Kind)
        {
            case ParameterKind.ServiceProvider:
                return "services";
            case ParameterKind.OptionalService:
                return ServiceProviderExtensions + ".GetService<" + parameter.TypeName + ">(services)";
            default:
                return ServiceProviderExtensions + ".GetRequiredService<" + parameter.TypeName + ">(services)";
        }
    }

    /// <summary>Writes the last argument: an options lambda, or null when the attribute sets no options.</summary>
    private static void AppendConfigure(StringBuilder source, JobModel job)
    {
        List<string> statements = new List<string>();

        if (job.Queue is not null)
        {
            statements.Add("options.Queue = " + ToStringLiteral(job.Queue) + ";");
        }

        if (job.MaxAttempts > 0)
        {
            statements.Add("options.MaxAttempts = " + ToIntLiteral(job.MaxAttempts) + ";");
        }

        if (job.TimeoutSeconds > 0)
        {
            statements.Add("options.Timeout = global::System.TimeSpan.FromSeconds(" + ToIntLiteral(job.TimeoutSeconds) + ");");
        }

        if (statements.Count == 0)
        {
            source.AppendLine("                configure: null);");
            return;
        }

        source.AppendLine("                configure: options =>");
        source.AppendLine("                {");
        foreach (string statement in statements)
        {
            source.AppendLine("                    " + statement);
        }

        source.AppendLine("                });");
    }

    private static string ToIntLiteral(int value)
    {
        return value.ToString(CultureInfo.InvariantCulture);
    }

    /// <summary>Writes a C# string literal, escaping backslashes and quotes.</summary>
    private static string ToStringLiteral(string value)
    {
        string escaped = value.Replace("\\", "\\\\").Replace("\"", "\\\"");
        return "\"" + escaped + "\"";
    }
}
